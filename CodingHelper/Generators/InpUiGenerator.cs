        private InpUiGenerator() { }

        public void Generate(SourceProductionContext context, UserInterfaceInfo info, Version tsmVersion,
            string projectDir) {
            var arguments = info.Arguments;

            var builder = new StringBuilder();
            builder.AppendLine(Head(info.ClassInfo.NameSpace, info.PluginName));
            var pageIndex = Parameters(ref builder, 0,
                [.. arguments.Where(kvp => kvp.Key is "int" or "double" or "string")]);
            pageIndex = PartsPlates(ref builder, pageIndex,
                [.. arguments.Where(kvp => kvp.Key is "PartAttribute" or "PlateAttribute")]);
            pageIndex = Chamfers(ref builder, pageIndex,
                [.. arguments.Where(kvp => kvp.Key is "ChamferAttribute").SelectMany(kvp => kvp.Value)]);
            pageIndex = Bolts(ref builder, pageIndex,
                [.. arguments.Where(kvp => kvp.Key is "BoltAttribute").SelectMany(kvp => kvp.Value)], tsmVersion);
            pageIndex = Studs(ref builder, pageIndex,
                [.. arguments.Where(kvp => kvp.Key is "StudAttribute").SelectMany(kvp => kvp.Value)]);
            _ = Welds(ref builder, pageIndex,
                [.. arguments.Where(kvp => kvp.Key is "WeldAttribute").SelectMany(kvp => kvp.Value)]);
            builder.AppendLine(Tail());

            context.AddSource("InpUi.g.cs", SourceText.From(builder.ToString(), Encoding.UTF8));
        }

        private static string Head(string nameSpace, string pluginName) {
            return
#if DEBUG
                $"// <auto-generated> at {DateTime.Now}\r\n" +
#else
                $"// <auto-generated>\r\n" +
#endif
                $"namespace {nameSpace} {{\r\n" +
                $"    public static class InpUi {{\r\n" +
                $"        public const string Definition = \r\n" +
                $"            \"\"\"\r\n" +
                $"            page(\"TeklaStructures\", \"\")\r\n" +
                $"            {{\r\n" +
                $"                joint(1, \"{pluginName}\")\r\n" +
                $"                {{";
        }

        private static int Parameters(ref StringBuilder builder, int prePageIndex,
            KeyValuePair<string, IdSet>[] keyValuePairs) {

            if (keyValuePairs is null || keyValuePairs.Length is 0) return 0;
            if (prePageIndex is 3) prePageIndex = 4;

            builder.AppendLine(
                $"                    tab_page(\"\", \"Parameters\", {prePageIndex + 1})\r\n" +
                $"                    {{");

            var index = -1;
            foreach (var kvp in keyValuePairs) {
                var dataType = kvp.Key switch {
                    "int" => "integer",
                    "double" => "distance",
                    "string" => "string",
                    _ => throw new ArgumentOutOfRangeException()
                };
                var dialogDataType = kvp.Key switch {
                    "int" or "double" => "number",
                    "string" => "text",
                    _ => throw new ArgumentOutOfRangeException()
                };
                var idSet = kvp.Value;

                foreach (var id in idSet) {
                    index++;
                    var column = index / 20;
                    var row = index % 20;
                    var labelX = column * 338;
                    var paramX = labelX + 240;
                    var y = row * 28;

                    builder.AppendLine(
                        $"                        attribute(\"\", \"{ToPropertyNameStyle(id)}\", label, \"%s\", none, none, \"0\", \"0\", {labelX}, {y})\r\n" +
                        $"                        parameter(\"\", \"{id}\", {dataType}, {dialogDataType}, {paramX}, {y}, 80)");
                }
            }

            builder.AppendLine($"                    }}");

            return prePageIndex + 1;
        }

        private static int PartsPlates(ref StringBuilder builder, int prePageIndex,
            KeyValuePair<string, IdSet>[] keyValuePairs) {

            if (keyValuePairs is null || keyValuePairs.Length is 0) return prePageIndex;
            if (prePageIndex is 3) prePageIndex = 4;

            builder.AppendLine(
                $"                    tab_page(\"\", \"Parts\", {prePageIndex + 1})\r\n" +
                $"                    {{\r\n" +
                $"                        attribute(\"\", \"Finish\", label, \"%s\", none, none, \"0\", \"0\", 850, 0)\r\n" +
                $"                        attribute(\"\", \"Class\", label, \"%s\", none, none, \"0\", \"0\", 954, 0)");

            var partCnt = 0;
            var plateCnt = 0;
            foreach (var kvp in keyValuePairs) {
                var attribute = kvp.Key;
                var idSet = kvp.Value;

                foreach (var id in idSet) {
                    switch (attribute) {
                    case "PartAttribute":
                        partCnt++;
                        AppendPart(ref builder, id, partCnt, (partCnt + plateCnt) * 2 - 1);
                        break;
                    case "PlateAttribute":
                        plateCnt++;
                        AppendPlate(ref builder, id, plateCnt, (partCnt + plateCnt) * 2 - 1);
                        break;
                    }
                }
            }

            builder.AppendLine($"                    }}");

            return prePageIndex + 1;
        }

        private static void AppendPart(ref StringBuilder builder, string id, int inpNum, int row) {
            var y = row * 24;
            builder.AppendLine(
                $"                        profile(\"{ToPropertyNameStyle(id)}\", PT{id}PRF, pt{inpNum}p, PT{id}MATL, pt{inpNum}a, PT{id}NAME, {row})\r\n" +
                $"                        parameter(\"\", \"PT{id}FNSH\", string, text, 834, {y}, 80)\r\n" +
                $"                        parameter(\"\", \"PT{id}CLS\", integer, number, 944, {y}, 60)");
        }

        private static void AppendPlate(ref StringBuilder builder, string id, int inpNum, int row) {
            var y = row * 24;
